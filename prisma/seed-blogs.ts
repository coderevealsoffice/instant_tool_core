async function main() {
  console.log("Starting to seed blog categories and posts...");

  // 1. Upsert Categories
  const categoriesToCreate = ["Education", "Business", "Creators", "Technology"];
  const categoryMap = new Map();

  for (const name of categoriesToCreate) {
    const slug = name.toLowerCase();
    const category = await prisma.blogCategory.upsert({
      where: { slug },
      update: {},
      create: { name, slug }
    });
    categoryMap.set(name, category.id);
    console.log(`✅ Ensured category: ${name}`);
  }

  // 2. Upsert Blogs
  for (const blog of blogs) {
    const categoryId = categoryMap.get(blog.categoryName);
    
    await prisma.blogPost.upsert({
      where: { slug: blog.slug },
      update: {
        title: blog.title,
        excerpt: blog.excerpt,
        content: blog.content,
        author: blog.author,
        image: blog.image,
        metaTitle: blog.metaTitle,
        metaDesc: blog.metaDesc,
        isPublished: true,
        categoryId: categoryId,
      },
      create: {
        slug: blog.slug,
        title: blog.title,
        excerpt: blog.excerpt,
        content: blog.content,
        author: blog.author,
        image: blog.image,
        metaTitle: blog.metaTitle,
        metaDesc: blog.metaDesc,
        isPublished: true,
        categoryId: categoryId,
      }
    });
    console.log(`✅ Seeded blog: ${blog.title}`);
  }

  console.log("🎉 All blogs successfully seeded!");
}

